export const emojiRouter = Router();

// GET /api/emojis - returns categorized emojis and quick reactions
emojiRouter.get('/', (req: Request, res: Response) => {
  const { category } = req.query;

  let items = EMOJI_LIST;
  if (typeof category === 'string' && category.trim()) {
    items = items.filter(e => e.category.toLowerCase() === category.toLowerCase());
  }

  // Group by category
  const categorized: Record<string, EmojiItem[]> = {};
  for (const cat of EMOJI_CATEGORIES) {
    categorized[cat] = items.filter(e => e.category === cat);
  }

  return res.json({
    categories: EMOJI_CATEGORIES,
    quickReactions: QUICK_REACTIONS,
    grouped: categorized,
    total: items.length,
    emojis: items,
  });
});

// GET /api/emojis/search?q=searchterm
emojiRouter.get('/search', (req: Request, res: Response) => {
  const q = String(req.query.q || '').trim().toLowerCase();
  if (!q) {
    return res.json({ results: EMOJI_LIST.slice(0, 50) });
  }

  const results = EMOJI_LIST.filter(item => {
    return (
      item.emoji === q ||
      item.name.toLowerCase().includes(q) ||
      item.keywords.some(k => k.toLowerCase().includes(q))
    );
  });

  return res.json({ query: q, count: results.length, results });
});
